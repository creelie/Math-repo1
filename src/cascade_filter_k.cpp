// ---------- row processing ----------

static long long rows = 0;
static long long survivors = 0;
static long long skipped = 0;

static void process(const array<int, K>& base, FILE* out) {
    ++rows;

    const u64* gp[K][2];
    for (int i = 0; i < K; ++i) {
        for (int b = 0; b < 2; ++b) {
            gp[i][b] = gm[static_cast<size_t>(base[static_cast<size_t>(i)])]
                              [static_cast<size_t>(b)]
                                  .data();
        }
    }

    vector<int> improperA;
    improperA.reserve(NB);
    const bool full = cover_cube(
        [&](int i, int b, int T) { return mbit(gp[i][b], T); }, P, true,
        improperA);

    if (!full) {
        ++survivors;
        cascade(base, improperA, out);
    }
}

struct TPre {
    u64 wm;
    int hiSel;
    int hiVal;
    bool dead;
};

static constexpr int EXT = K - 1;  // reducible variant: EXT-class cover + one extension class
static vector<TPre> preExt;

static void process_ext(array<int, K>& base, FILE* out) {
    const u64* gp[EXT][2];
    for (int i = 0; i < EXT; ++i) {
        for (int b = 0; b < 2; ++b) {
            gp[i][b] = gm[static_cast<size_t>(base[static_cast<size_t>(i)])]
                              [static_cast<size_t>(b)]
                                  .data();
        }
    }

    preExt.assign(static_cast<size_t>(P + 1), TPre{});
    for (int T = 1; T <= P; ++T) {
        TPre q{~u64{0}, 0, 0, false};
        for (int i = 0; i < EXT; ++i) {
            const bool g0 = mbit(gp[i][0], T);
            const bool g1 = mbit(gp[i][1], T);
            if (g0 && g1) continue;
            if (!g0 && !g1) {
                q.dead = true;
                break;
            }
            const int ai = g1 ? 1 : 0;
            if (i < 6) {
                q.wm &= ai ? ~PAT0[i] : PAT0[i];
            } else {
                q.hiSel |= 1 << (i - 6);
                if (ai) q.hiVal |= 1 << (i - 6);
            }
        }
        preExt[static_cast<size_t>(T)] = q;
    }

    vector<int> improperA;
    improperA.reserve(NB);
    for (int v = 1; v <= NC; ++v) {
        base[EXT] = v;
        ++rows;

        const u64* e0 = gm[static_cast<size_t>(v)][0].data();
        const u64* e1 = gm[static_cast<size_t>(v)][1].data();

        u64 bm[NWCUBE];
        std::memset(bm, 0, sizeof(bm));
        bm[0] |= u64{1};
        for (int i = 0; i < K; ++i) {
            const int a = 1 << i;
            bm[a >> 6] |= u64{1} << (a & 63);
        }

        int firstNF = 0;
        for (int T = 1; T <= P && firstNF < NWCUBE; ++T) {
            const TPre& q = preExt[static_cast<size_t>(T)];
            if (q.dead) continue;

            const bool g0 = mbit(e0, T);
            const bool g1 = mbit(e1, T);
            if (!g0 && !g1) continue;

            int hiSel = q.hiSel;
            int hiVal = q.hiVal;
            if (!(g0 && g1)) {
                hiSel |= 1 << (EXT - 6);
                if (g1) hiVal |= 1 << (EXT - 6);
            }

            const int freeb = ~hiSel & (NWCUBE - 1);
            for (int s = freeb;; s = (s - 1) & freeb) {
                bm[s | hiVal] |= q.wm;
                if (!s) break;
            }
            while (firstNF < NWCUBE && bm[firstNF] == ~u64{0}) ++firstNF;
        }

        if (firstNF >= NWCUBE) continue;

        improperA.clear();
        for (int j = 0; j < NWCUBE; ++j) {
            u64 z = ~bm[j];
            while (z) {
                improperA.push_back(j * 64 + __builtin_ctzll(z));
                z &= z - 1;
            }
        }

        ++survivors;
        cascade(base, improperA, out);
    }
}

// ---------- independent scalar oracle self-test ----------

struct XorShift64 {
    uint64_t s = UINT64_C(0x8f3f73b5cf1c9ade);
    uint64_t next() {
        s ^= s << 13;
        s ^= s >> 7;
        s ^= s << 17;
        return s;
    }
};

static vector<int> scalar_uncovered(
    const vector<array<uint8_t, K * 2>>& allow, bool preOddScreen) {
    vector<int> result;
    for (int a = 0; a < NB; ++a) {
        if (preOddScreen && __builtin_popcount(static_cast<unsigned>(a)) <= 1)
            continue;

        bool covered = false;
        for (const auto& time : allow) {
            bool allGood = true;
            for (int i = 0; i < K; ++i) {
                const int b = (a >> i) & 1;
                if (!time[static_cast<size_t>(2 * i + b)]) {
                    allGood = false;
                    break;
                }
            }
            if (allGood) {
                covered = true;
                break;
            }
        }
        if (!covered) result.push_back(a);
    }
    return result;
}

static bool scalar_old_tight(const array<int, K>& base) {
    const std::set<int> target(base.begin(), base.end());
    for (int g = 1; g < P; ++g) {
        std::set<int> candidate;
        for (int i = 1; i <= K; ++i) {
            const int x = static_cast<int>((ll)g * i % P);
            candidate.insert(std::min(x, P - x));
        }
        if (candidate == target) return true;
    }
    return false;
}

// good() exactly as the v2/v3 generic lift lambda.
static inline bool generic_lift_good(const array<int, K>& w, int M, int i,
                                     int b, int T) {
    const int M2 = 2 * M;
    const ll v = w[static_cast<size_t>(i)] + (b ? (ll)M : 0);
    const int y = static_cast<int>((ll)T * v % M2);
    const int d = std::min(y, M2 - y);
    return (K + 1) * d >= M2;
}

// Part C: on real cascade trees, verify (a) specialized == generic and
// (b) every even time is dead. Returns visited node count, -1 on failure.
static long long selftest_lift_tree(array<int, K>& w, int M, int level,
                                    long long budget) {
    if (budget <= 0) return 0;
    if (q2_proper_parent(w)) return 1;

    vector<int> refA;
    vector<int> gotA;
    const bool refFull = cover_cube(
        [&](int i, int b, int T) { return generic_lift_good(w, M, i, b, T); },
        M, false, refA);
    const bool gotFull = cover_cube_lift(w, M, gotA);

    if (refFull != gotFull || refA != gotA) {
        std::fprintf(stderr,
                     "SELFTEST FAIL lift kernel P=%d M=%d level=%d "
                     "ref=%zu got=%zu\n",
                     P, M, level, refA.size(), gotA.size());
        return -1;
    }

    // Even-time deadness on this production-shaped parent.
    for (int T = 2; T <= M; T += 2) {
        bool dead = false;
        for (int i = 0; i < K && !dead; ++i) {
            if (!generic_lift_good(w, M, i, 0, T) &&
                !generic_lift_good(w, M, i, 1, T)) {
                dead = true;
            }
            // For even T the two choices must agree.
            if (generic_lift_good(w, M, i, 0, T) !=
                generic_lift_good(w, M, i, 1, T)) {
                std::fprintf(stderr,
                             "SELFTEST FAIL even-time choice mismatch "
                             "P=%d M=%d T=%d\n",
                             P, M, T);
                return -1;
            }
        }
        if (!dead) {
            std::fprintf(stderr,
                         "SELFTEST FAIL even time not dead P=%d M=%d T=%d\n",
                         P, M, T);
            return -1;
        }
    }

    long long visited = 1;
    if (level + 1 >= MAX_LIFT_EXP) return visited;

    for (const int a : refA) {
        for (int i = 0; i < K; ++i) {
            if ((a >> i) & 1) w[static_cast<size_t>(i)] += M;
        }
        const long long sub =
            selftest_lift_tree(w, 2 * M, level + 1, budget - visited);
        for (int i = 0; i < K; ++i) {
            if ((a >> i) & 1) w[static_cast<size_t>(i)] -= M;
        }
        if (sub < 0) return -1;
        visited += sub;
        if (visited >= budget) break;
    }
    return visited;
}

// A random level-1 cover of Z_P: the first nrep coordinates are class 1 (the
// shape of the deep rows), the rest are chosen greedily so that every time
// T = 1..P-1 has some speed within 1/(K+1) of an integer. Returns false if K
// speeds do not suffice.
static bool random_cover_base(XorShift64& rng, array<int, K>& base, int nrep) {
    vector<char> cov(static_cast<size_t>(P), 0);
    auto mark = [&](int v) {
        for (int T = 1; T < P; ++T) {
            const int y = static_cast<int>((static_cast<ll>(T) * v) % P);
            const int d = std::min(y, P - y);
            if ((K + 1) * d < P) cov[static_cast<size_t>(T)] = 1;
        }
    };
    int n = 0;
    for (; n < nrep && n < K; ++n) { base[static_cast<size_t>(n)] = 1; mark(1); }
    int R = 0;
    while ((K + 1) * (R + 1) < P) ++R;
    while (true) {
        const int start = 1 + static_cast<int>(rng.next() % static_cast<uint64_t>(P - 1));
        int T = -1;
        for (int s = 0; s < P - 1; ++s) {
            const int t = 1 + (start - 1 + s) % (P - 1);
            if (!cov[static_cast<size_t>(t)]) { T = t; break; }
        }
        if (T < 0) break;
        if (n == K) return false;
        int inv = 1;
        while ((static_cast<ll>(inv) * T) % P != 1) ++inv;
        // among the speeds that cover T, take one covering the most open times
        int best = -1, bestGain = -1;
        for (int r = 1; r <= R; ++r) {
            int v = static_cast<int>((static_cast<ll>(r) * inv) % P);
            if (v > P - v) v = P - v;
            int gain = 0;
            for (int t = 1; t < P; ++t) {
                const int y = static_cast<int>((static_cast<ll>(t) * v) % P);
                if ((K + 1) * std::min(y, P - y) < P && !cov[static_cast<size_t>(t)]) ++gain;
            }
            gain = 4 * gain + static_cast<int>(rng.next() % 4);
            if (gain > bestGain) { bestGain = gain; best = v; }
        }
        base[static_cast<size_t>(n++)] = best;
        mark(best);
    }
    for (; n < K; ++n)
        base[static_cast<size_t>(n)] = 1 + static_cast<int>(rng.next() % static_cast<uint64_t>(NC));
    return true;
}

static int run_selftest() {
    init_pats();
    init_binom();
    XorShift64 rng;

    for (int tc = 0; tc < 300; ++tc) {
        const int Tmax = 1 + static_cast<int>(rng.next() % 96);
        const bool pre = (rng.next() & 1) != 0;
        vector<array<uint8_t, K * 2>> allow(static_cast<size_t>(Tmax));

        for (int T = 0; T < Tmax; ++T) {
            for (int i = 0; i < K; ++i) {
                const unsigned mode = static_cast<unsigned>(rng.next() & 3);
                allow[static_cast<size_t>(T)][static_cast<size_t>(2 * i)] =
                    static_cast<uint8_t>(mode == 1 || mode == 3);
                allow[static_cast<size_t>(T)][static_cast<size_t>(2 * i + 1)] =
                    static_cast<uint8_t>(mode == 2 || mode == 3);
            }
        }

        vector<int> got;
        const bool full = cover_cube(
            [&](int i, int b, int T) {
                return allow[static_cast<size_t>(T - 1)]
                            [static_cast<size_t>(2 * i + b)] != 0;
            },
            Tmax, pre, got);
        const vector<int> want = scalar_uncovered(allow, pre);

        if (got != want || full != want.empty()) {
            std::fprintf(stderr,
                         "SELFTEST FAIL case=%d Tmax=%d pre=%d got=%zu "
                         "want=%zu\n",
                         tc, Tmax, pre ? 1 : 0, got.size(), want.size());
            return 1;
        }
    }

    // Tight lookup versus the exact old std::set implementation.
    for (const int prime : {31, 61, 167}) {
        P = prime;
        NC = (P - 1) / 2;
        build_tight_keys();

        for (int tc = 0; tc < 1000; ++tc) {
            array<int, K> base{};
            for (int i = 0; i < K; ++i) {
                base[static_cast<size_t>(i)] =
                    1 + static_cast<int>(rng.next() %
                                         static_cast<uint64_t>(NC));
            }
            if (tc < K) base[static_cast<size_t>(tc)] = base[0];

            if (is_tight_base(base) != scalar_old_tight(base)) {
                std::fprintf(stderr,
                             "SELFTEST FAIL tight lookup P=%d case=%d\n", P,
                             tc);
                return 1;
            }
        }

        for (int g = 1; g <= NC; ++g) {
            array<int, K> base{};
            for (int i = 1; i <= K; ++i) {
                const int x = static_cast<int>((ll)g * i % P);
                base[static_cast<size_t>(i - 1)] = std::min(x, P - x);
            }
            if (!is_tight_base(base) || !scalar_old_tight(base)) {
                std::fprintf(stderr,
                             "SELFTEST FAIL positive tight lookup P=%d "
                             "g=%d\n",
                             P, g);
                return 1;
            }
        }
    }

    // Part C: lift kernel on real cascade trees.
    long long totalParents = 0;
    for (const int prime : {31, 61, 179}) {
        P = prime;
        NC = (P - 1) / 2;
        build_masks();
        build_tight_keys();

        long long parents = 0;
        for (int bc = 0; bc < 4000 && parents < 4000; ++bc) {
            array<int, K> base{};
            // random level-1 covers; odd cases start with repeated class 1
            // (the shape of the deep rows), which leaves improper lifts
            const int nrep = (bc & 1) ? 2 + static_cast<int>(rng.next() % 7) : 0;
            if (!random_cover_base(rng, base, nrep)) continue;

            const u64* gp[K][2];
            for (int i = 0; i < K; ++i) {
                for (int b = 0; b < 2; ++b) {
                    gp[i][b] =
                        gm[static_cast<size_t>(
                               base[static_cast<size_t>(i)])]
                          [static_cast<size_t>(b)]
                              .data();
                }
            }

            vector<int> l2imp;
            const bool full = cover_cube(
                [&](int i, int b, int T) { return mbit(gp[i][b], T); }, P,
                true, l2imp);
            if (full) continue;

            for (const int a : l2imp) {
                array<int, K> w{};
                for (int i = 0; i < K; ++i) {
                    const int v = base[static_cast<size_t>(i)];
                    const int bit = (a >> i) & 1;
                    w[static_cast<size_t>(i)] = (v % 2 == bit) ? v : v + P;
                }
                const long long sub =
                    selftest_lift_tree(w, 2 * P, 1, 4000 - parents);
                if (sub < 0) return 1;
                parents += sub;
                if (parents >= 4000) break;
            }
        }
        totalParents += parents;
    }

    // Part D: the symmetry-reduced weighted counts equal the unreduced counts.
    long long symRows = 0, symShift = 0, symRepeated = 0, symDeep = 0;
    {
        P = 179; NC = (P - 1) / 2;
        build_masks();
        // first the 89 extensions of a real 14-class cover of the P = 179
        // gate (its x = 1 extension reaches level 8), then random covers
        static const int seed179[K - 1] = {1, 1, 1, 2, 5, 11, 12, 37, 41, 70, 75, 80, 85, 86};
        for (int bc = 0; bc < 3000 && symRows < NC + 60; ++bc) {
            array<int, K> base{};
            if (bc < NC) {
                for (int i = 0; i < K - 1; ++i) base[static_cast<size_t>(i)] = seed179[i];
                base[K - 1] = bc + 1;
            } else if (!random_cover_base(rng, base, static_cast<int>(rng.next() % 9))) continue;
            const u64* gp[K][2];
            for (int i = 0; i < K; ++i)
                for (int b = 0; b < 2; ++b)
                    gp[i][b] = gm[static_cast<size_t>(base[static_cast<size_t>(i)])][static_cast<size_t>(b)].data();
            vector<int> l2imp;
            if (cover_cube([&](int i, int b, int T) { return mbit(gp[i][b], T); }, P, true, l2imp)) continue;
            // reduced
            DfsScratch red;
            SymGroups G; sym_groups(base, G);
            for (const int a : l2imp) {
                const uint64_t wt = G.npair ? sym_weight(G, a) : 1;
                if (!wt) continue;
                array<int, K> w{};
                for (int i = 0; i < K; ++i) { const int v = base[static_cast<size_t>(i)]; w[static_cast<size_t>(i)] = (v % 2 == ((a >> i) & 1)) ? v : v + P; }
                dfs_lifts(w, 2 * P, 1, wt, red);
            }
            // unreduced reference: plain recursion over every improper child
            array<unsigned __int128, MAX_LIFT_EXP + 1> ref{};
            unsigned __int128 refShift = 0;
            struct Rec {
                static void go(array<int, K>& w, int M, int level, array<unsigned __int128, MAX_LIFT_EXP + 1>& c, unsigned __int128& sh) {
                    vector<int> imp; cover_cube_lift(w, M, imp);
                    for (const int a : imp) {
                        for (int i = 0; i < K; ++i) if ((a >> i) & 1) w[static_cast<size_t>(i)] += M;
                        if (!q2_proper_parent(w)) {
                            if (shift_proper(w, level + 1)) ++sh;
                            else { ++c[static_cast<size_t>(level + 1)]; if (level + 1 < MAX_LIFT_EXP) go(w, 2 * M, level + 1, c, sh); }
                        }
                        for (int i = 0; i < K; ++i) if ((a >> i) & 1) w[static_cast<size_t>(i)] -= M;
                    }
                }
            };
            for (const int a : l2imp) {
                array<int, K> w{};
                for (int i = 0; i < K; ++i) { const int v = base[static_cast<size_t>(i)]; w[static_cast<size_t>(i)] = (v % 2 == ((a >> i) & 1)) ? v : v + P; }
                Rec::go(w, 2 * P, 1, ref, refShift);
            }
            for (int l = 2; l <= MAX_LIFT_EXP; ++l)
                if (ref[static_cast<size_t>(l)] != red.count[static_cast<size_t>(l)]) {
                    std::fprintf(stderr, "SELFTEST FAIL symmetry count level %d\n", l); return 1;
                }
            if (refShift != red.shift) { std::fprintf(stderr, "SELFTEST FAIL symmetry shift count\n"); return 1; }
            ++symRows;
            symShift += static_cast<long long>(refShift);
            symRepeated += G.npair ? 1 : 0;
            symDeep += ref[3] ? 1 : 0;
        }
    }

    // Part E: shift_proper against a brute-force count of forbidden shifts
    // (largest number of the d points q*x/d mod 1 in an open arc of length
    // 2/(K+1), maximised over the arc position).
    long long shiftCases = 0, shiftTrue = 0;
    for (int tc = 0; tc < 20000; ++tc) {
        const int level = 2 + static_cast<int>(rng.next() % 4);
        array<int, K> w{};
        for (int i = 0; i < K; ++i) {
            const int v = static_cast<int>(rng.next() % 7);
            w[static_cast<size_t>(i)] = (1 + 2 * static_cast<int>(rng.next() % 50)) << (v > level + 1 ? level + 1 : v);
        }
        bool want = false;
        for (int j = 2; j <= level && !want; ++j) {
            const int d = 1 << j;
            int forb = 0;
            for (int i = 0; i < K; ++i) {
                const int x = w[static_cast<size_t>(i)] % d;
                if (x == 0) continue;
                int best = 0;
                for (int st = 0; st < d; ++st) {
                    int c = 0;
                    for (int q = 0; q < d; ++q) {
                        const int r = static_cast<int>((static_cast<ll>(q) * x) % d);
                        const int diff = ((r - st) % d + d) % d;
                        if ((K + 1) * diff < 2 * d) ++c;
                    }
                    if (c > best) best = c;
                }
                forb += best;
            }
            if (forb < d) want = true;
        }
        if (want != shift_proper(w, level)) { std::fprintf(stderr, "SELFTEST FAIL shift lemma case %d\n", tc); return 1; }
        ++shiftCases; shiftTrue += want;
    }

    std::fprintf(stderr,
                 "SELFTEST OK: 300 exact cover cases; 3-prime tight lookup "
                 "audit; lift kernel verified on %lld real cascade parents "
                 "(specialized == generic, all even times dead); symmetry "
                 "reduction equals the unreduced counts on %lld rows (%lld with "
                 "repeated classes, %lld reaching level 8, %lld lifts settled "
                 "by the shift lemma); shift test equals the brute-force count "
                 "on %lld cases (%lld settled)\n",
                 totalParents, symRows, symRepeated, symDeep, symShift,
                 shiftCases, shiftTrue);
    return 0;
}

// ---------- input ----------

static int hexv(char c) {
    return c <= '9' ? c - '0' : c - 'a' + 10;
}

int main(int argc, char** argv) {
    if (argc == 2 && std::strcmp(argv[1], "--selftest") == 0) {
        return run_selftest();
    }

    if (argc < 4) {
        std::fprintf(stderr,
                     "usage: cascade_filter_k P filter|filterext file...\n");
        return 2;
    }

    P = std::atoi(argv[1]);
    NC = (P - 1) / 2;
    if (P < 17 || P > 2039 || P % 2 == 0) {
        std::fprintf(stderr, "bad P\n");
        return 2;
    }

    const bool ext12 = std::strcmp(argv[2], "filterext") == 0;
    if (!ext12 && std::strcmp(argv[2], "filter") != 0) {
        std::fprintf(stderr, "bad mode\n");
        return 2;
    }

    init_pats();
    init_binom();
    build_masks();
    build_tight_keys();

    const int nin = ext12 ? EXT : K;
    for (int f = 3; f < argc; ++f) {
        FILE* in = std::fopen(argv[f], "r");
        if (!in) {
            std::fprintf(stderr, "cannot open %s\n", argv[f]);
            return 2;
        }

        char line[128];
        while (std::fgets(line, sizeof(line), in)) {
            const int len = static_cast<int>(std::strcspn(line, "\r\n"));
            int hexw;
            if (len == 2 * nin) {
                hexw = 2;
            } else if (len == 4 * nin) {
                hexw = 4;
            } else {
                if (len > 0) ++skipped;
                continue;
            }

            array<int, K> base{};
            bool ok = true;
            for (int i = 0; i < nin; ++i) {
                int v = 0;
                for (int h = 0; h < hexw; ++h) {
                    v = v * 16 + hexv(line[hexw * i + h]);
                }
                if (v < 1 || v > NC) {
                    ok = false;
                    break;
                }
                base[static_cast<size_t>(i)] = v;
            }
            if (!ok) {
                std::fprintf(stderr, "bad class in %s: %.*s\n", argv[f], len,
                             line);
                std::fclose(in);
                return 3;
            }

            if (ext12) {
                process_ext(base, stdout);
            } else {
                process(base, stdout);
            }
        }

        std::fclose(in);
        std::fprintf(stderr, "file %s done: rows=%lld survivors=%lld\n",
                     argv[f], rows, survivors);
    }

    std::fprintf(stderr, "TOTAL rows=%lld survivors=%lld shiftkilled=", rows, survivors);
    print_u128(stderr, shift_killed);
    std::fprintf(stderr, " maxlevel=%d\n", 1 << MAX_LIFT_EXP);
#ifdef CASCADE_CONSERVATIVE
    if (capped) {
        std::fprintf(stderr,
                     "NOTE: %lld rows hit LIFT_CAP (properness proof "
                     "abandoned, marked PERSISTENT)\n",
                     capped);
    }
#endif
    if (skipped) {
        std::fprintf(stderr, "ERROR: %lld malformed non-empty lines skipped\n",
                     skipped);
        return 3;
    }
    return 0;
}
