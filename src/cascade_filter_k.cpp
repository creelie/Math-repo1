// cascade_filter_k.cpp -- generic-K port of lrc14/cascade_filter_v4.cpp
//
// Differences from v4 (K=13, divisor 14): K is a compile-time macro (-DK=14
// default), every literal 14 became K+1 and the reducible extension variant
// (formerly filter12 / process12) uses EXT = K-1 classes plus one extension
// class (mode filterext). Kernels, cascade and self-test are otherwise the
// v4 code. Covering condition: class v covers time T at level M iff
// (K+1)*dist_M(T*v) < M; "good" (witness) is the complement (K+1)*d >= M.
//
// v4 = v3 (exact DFS cascade, tight-orbit lookup, no LIFT_CAP in the exact
// build) + a division-free odd-time lift kernel.
//
// Lift kernel derivation (exact, not heuristic):
//   For a lift M -> 2M set N = 2M and A = ceil(N/(K+1)). Choice b in {0,1}
//   for coordinate i has phase y_b = T*(w_i + b*M) mod N and is good iff
//   A <= y_b <= N - A  (identical to (K+1)*min(y, N-y) >= N).
//   Since y_1 = y_0 + T*M mod N:
//    - EVEN T = 2S: T*M mod N = 0, so both choices share y = 2*(S*w_i mod M).
//      The condition reduces to the PARENT's level-M goodness at time S.
//      Every parent reaching the lift is improper at level M (uncovered by
//      times 1..M/2 at its own construction; the pre-odd gcd screen only adds
//      covered vectors and dead/skipped times cover nothing, so uncoveredness
//      w.r.t. the full time set holds inductively). Hence for every S some
//      coordinate is bad, an even time covers nothing, and even times are
//      skipped EXACTLY.
//    - ODD T: T*M mod N = M, so y_1 = y_0 + M mod N. bad0 iff y_0 < A or
//      y_0 > N-A; bad1 iff M-A < y_0 < M+A. The two bad regions are disjoint
//      (A < M/2), so a coordinate is free, forced-0 or forced-1, never dead,
//      and only y_0 is needed.
//   y_0 is advanced over odd T by the recurrence y += 2*w_i (mod N): no
//   multiplications or divisions remain in the inner loop.
//
// The selftest (--selftest) validates, in addition to the v3 checks:
//   part C: on real cascade trees at P=29 and P=61 (parents generated by the
//   generic reference path), for every parent (a) the generic all-times
//   cover and the specialized odd-only kernel produce identical uncovered
//   sets, and (b) every even time is dead, confirming the theorem on
//   production-shaped inputs.
//
// Exact certificate build:
//   g++ -O3 -march=native -std=c++17 -DK=14 -o cascade_filter_k14 cascade_filter_k.cpp
//
// Conservative scouting build (capped BFS semantics):
//   g++ -O3 -march=native -std=c++17 -DK=14 -DCASCADE_CONSERVATIVE
//       -o cascade_filter_k14_conservative cascade_filter_k.cpp
//
// Usage (row files: one row per line, 2 or 4 hex digits per class):
//   cascade_filter_k P filter|filterext file...

